# 生成 BASE_PROMPT 函数
def generate_base_prompt(title, segment_text, tags, _format=None, style=None, extras=None):
    # 生成 Base Prompt 开头部分
    prompt = BASE_PROMPT.format(
        video_title=title,
        segment_text=segment_text,
        tags=tags
    )

    # 添加用户选择的格式
    if _format:
        prompt += "\n" + "\n".join([get_format_function(f) for f in _format])

    # 根据用户选择的笔记风格添加描述
    if style:
        style_text = get_style_format(style)
        # Obsidian 风格指令里含动态占位符：视频标题 / 当天日期 / 年份
        if style in ('obsidian_deep', 'obsidian_quick'):
            today = datetime.date.today()
            style_text = style_text.replace('{video_title}', title or '未知')
            style_text = style_text.replace('{today}', today.isoformat())
            style_text = style_text.replace('{year}', str(today.year))
        prompt += "\n" + style_text

    # 添加额外内容
    if extras:
        prompt += f"\n{extras}"
    return prompt


# 获取格式函数
def get_format_function(format_type):
    format_map = {
        'toc': get_toc_format,
        'link': get_link_format,
        'screenshot': get_screenshot_format,
        'summary': get_summary_format,
        'condensed': get_condensed_format
    }
    return format_map.get(format_type, lambda: '')()


